def parse(ref):
    """'26:1-5,14-16' or '9:35-10:15' -> [[(c,v),(c,v)],...]"""
    if not ref: return []
    out=[];cur=None
    for part in ref.split(","):
        part=part.strip()
        if ":" in part.split("-")[0]:
            cur=int(part.split(":")[0])
        m=re.match(r"^(?:(\d+):)?(\d+)(?:-(?:(\d+):)?(\d+))?$",part)
        c1=int(m.group(1)) if m.group(1) else cur
        v1=int(m.group(2))
        c2=int(m.group(3)) if m.group(3) else c1
        v2=int(m.group(4)) if m.group(4) else v1
        out.append([[c1,v1],[c2,v2]]); cur=c2
    return out

